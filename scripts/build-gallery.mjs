#!/usr/bin/env node
/**
 * Build the committed screenshot gallery from working QA captures.
 *
 * Why a build step rather than committing the PNGs directly: the raw captures
 * are 1400x900 PNGs at 1.5-2.5 MB each, and a repo that accumulates a few dozen
 * of those over a few sessions gets unpleasant to clone forever — git keeps
 * every version of a binary. These are re-encoded to ~150-350 KB JPEGs, which
 * is plenty for a README, a landing page, or a progress log.
 *
 * The source captures live in `qa-shots/`, which is gitignored on purpose: it is
 * scratch, it is rewritten on every QA run, and most of it is not worth keeping.
 * `docs/gallery/manifest.json` is the curated list — the decision about what is
 * worth keeping — and it is committed. A source that is missing (fresh clone, or
 * a capture not re-run) is skipped with a note rather than failing the build, so
 * this stays runnable by anyone.
 *
 * Usage:
 *   node scripts/build-gallery.mjs           # rebuild changed entries
 *   node scripts/build-gallery.mjs --force   # re-encode everything
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const galleryDir = path.join(repoRoot, 'docs', 'gallery');
const manifestPath = path.join(galleryDir, 'manifest.json');
const force = process.argv.includes('--force');

const MAX_WIDTH = 1400;
const JPEG_QUALITY = 82;

if (!fs.existsSync(manifestPath)) {
  console.error(`No manifest at ${path.relative(repoRoot, manifestPath)}`);
  process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
fs.mkdirSync(galleryDir, { recursive: true });

let built = 0;
let skipped = 0;
let missing = 0;

for (const entry of manifest.shots) {
  const source = path.join(repoRoot, entry.source);
  const target = path.join(galleryDir, `${entry.slug}.jpg`);
  if (!fs.existsSync(source)) {
    // Expected on a fresh clone: qa-shots/ is gitignored, so the committed JPEG
    // is the artifact and the PNG behind it may simply not be there.
    console.log(`  [skip] ${entry.slug} — source not present (${entry.source})`);
    missing += 1;
    continue;
  }
  if (!force && fs.existsSync(target)
      && fs.statSync(target).mtimeMs >= fs.statSync(source).mtimeMs) {
    skipped += 1;
    continue;
  }
  await sharp(source)
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .jpeg({ quality: JPEG_QUALITY, mozjpeg: true })
    .toFile(target);
  const kb = Math.round(fs.statSync(target).size / 1024);
  console.log(`  [built] ${entry.slug}.jpg (${kb} KB)`);
  built += 1;
}

// Regenerate the contact sheet so the gallery is browsable on GitHub without
// cloning. Sections keep their manifest order.
const bySection = new Map();
for (const entry of manifest.shots) {
  if (!fs.existsSync(path.join(galleryDir, `${entry.slug}.jpg`))) continue;
  if (!bySection.has(entry.section)) bySection.set(entry.section, []);
  bySection.get(entry.section).push(entry);
}

const lines = [
  '# Gallery',
  '',
  'Screenshots of the running app, kept as a progress record and as ready-made',
  'assets for the README and any landing page. Every image here was captured',
  'from the real application, not mocked up.',
  '',
  '**Do not edit this file by hand** — it is generated by',
  '`node scripts/build-gallery.mjs` from `manifest.json`. To add a shot, add an',
  'entry to the manifest and re-run.',
  '',
];
for (const [section, entries] of bySection) {
  lines.push(`## ${section}`, '');
  for (const entry of entries) {
    lines.push(`### ${entry.title}`, '');
    if (entry.caption) lines.push(entry.caption, '');
    lines.push(`![${entry.title}](${entry.slug}.jpg)`, '');
  }
}
fs.writeFileSync(path.join(galleryDir, 'README.md'), lines.join('\n'));

console.log(`\n  ${built} built, ${skipped} unchanged, ${missing} sources missing`);
console.log(`  ${path.relative(repoRoot, path.join(galleryDir, 'README.md'))} regenerated`);
